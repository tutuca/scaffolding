"""What HTTP serves, mirroring `commands.py` for argv.

Two tables. `RESOURCES` is the CRUD surface - a model, a URL prefix and the
basename `reverse()` resolves against - generated by `base.crud`. `ACTIONS` is the
handful that do something. The sample domain has no actions of its own.
"""

from django.db.models import Model
from rest_framework.viewsets import ViewSetMixin

from scaffolding.data import models

from .base import crud

# (url prefix, model, basename)
RESOURCES: list[tuple[str, type[Model], str]] = [
    ("notes", models.Note, "note"),
]

ACTIONS: list[tuple[str, type[ViewSetMixin], str]] = []

VIEWS: list[tuple[str, type[ViewSetMixin], str]] = [
    *[(prefix, crud(model), basename) for prefix, model, basename in RESOURCES],
    *ACTIONS,
]
