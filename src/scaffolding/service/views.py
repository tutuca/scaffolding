"""What HTTP serves, mirroring `commands.py` for argv.

Two tables. `RESOURCES` is the CRUD surface - a model, a URL prefix and the
basename `reverse()` resolves against - generated by `base.crud`, because twelve
viewsets whose whole body was `queryset` and `serializer_class` are a table, not
twelve files. `ACTIONS` is the handful that do something: an `@action`, a domain
call, a read model that is not a row.

The basename is written out rather than derived from the model, because it is
what `reverse("account-list")` resolves against and a rename there is a URL
change, not a refactor.
"""

from django.db.models import Model
from rest_framework.viewsets import ViewSetMixin

from scaffolding.data import models

from .base import crud
from .domain.billing import InvoiceViewSet
from .domain.planning.viewsets import GoalViewSet
from .domain.tax import PositionViewSet
from .payment import PaymentViewSet

# (url prefix, model, basename)
RESOURCES: list[tuple[str, type[Model], str]] = [
    ("clients", models.Client, "client"),
    ("contracts", models.Contract, "contract"),
    ("exchange-rates", models.ExchangeRate, "exchangerate"),
    ("accounts", models.Account, "account"),
    ("settlements", models.Settlement, "settlement"),
    ("monotributo/scale", models.MonotributoScale, "monotributoscale"),
    ("monotributo/status", models.MonotributoStatus, "monotributostatus"),
    ("autonomos-contributions", models.AutonomosContribution, "autonomoscontribution"),
    ("compensatory-rates", models.CompensatoryRate, "compensatoryrate"),
    ("legal-thresholds", models.LegalThreshold, "legalthreshold"),
    ("expenses", models.Expense, "expense"),
    ("obligations", models.Obligation, "obligation"),
]

# (url prefix, viewset, basename) - the ones with behaviour of their own.
ACTIONS: list[tuple[str, type[ViewSetMixin], str]] = [
    ("scaffolding", InvoiceViewSet, "invoice"),
    ("goals", GoalViewSet, "goal"),
    ("payments", PaymentViewSet, "payment"),
    ("monotributo/position", PositionViewSet, "monotributo-position"),
]

VIEWS: list[tuple[str, type[ViewSetMixin], str]] = [
    *[(prefix, crud(model), basename) for prefix, model, basename in RESOURCES],
    *ACTIONS,
]
